import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8942/?debug');
await page.waitForFunction(()=>window.__AI_BRIDGE__?.state().phase==='home');
await page.evaluate(()=>window.__AI_BRIDGE__.rigTest(true));
await page.waitForTimeout(1350);
await page.screenshot({path:'tools/shots/rig-block.png'});
await page.evaluate(()=>window.__AI_BRIDGE__.rigFreeze(true));
const a=await page.evaluate(()=>window.__AI_BRIDGE__.rigState());
await page.waitForTimeout(300);
assert.deepEqual(await page.evaluate(()=>window.__AI_BRIDGE__.rigState()),a);
await page.evaluate(()=>window.__AI_BRIDGE__.rigFreeze(false));
await page.waitForTimeout(2200);
const b=await page.evaluate(()=>window.__AI_BRIDGE__.rigState());
assert.ok(b.events.hit>=1);assert.ok(b.events.trail_on>=1);assert.ok(b.events.trail_off>=1);
assert.deepEqual(errors,[]); console.log('PASS block rig, freeze/resume, events',b);
await browser.close();
